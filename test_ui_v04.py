"""UI smoke tests for TASCA MVP 0.4. Run: python test_ui_v04.py"""
from pathlib import Path
from datetime import date,timedelta
from playwright.sync_api import sync_playwright
import re
ROOT=Path(__file__).resolve().parent
ROOT.joinpath('previews').mkdir(exist_ok=True)
def setup(page):
    html=(ROOT/'index.html').read_text(encoding='utf-8')
    html=re.sub(r'<script src="[^"]+" defer></script>', '', html)
    html=re.sub(r'<link[^>]+>', '', html)
    page.set_content(html,wait_until='domcontentloaded')
    page.add_style_tag(content=(ROOT/'styles.css').read_text(encoding='utf-8'))
    page.add_script_tag(content=(ROOT/'app.js').read_text(encoding='utf-8'))
    page.add_script_tag(content=(ROOT/'presentation.js').read_text(encoding='utf-8'))
results=[]
def check(label,condition):
    assert condition,label
    results.append('PASS '+label)

